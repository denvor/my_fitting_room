"""每个分类的固定指令与槽数。改动它等于改验收线，见设计文档 5.4 与 6.6。

分类 = 一次请求里除了人像还有几张参考图，以及那张（些）图当什么用。
指令里的"图像N"是**数组位置**：人像恒为图像1，参考图按槽序往后排，改顺序就是改指令的含义。
"""

# 千问图像编辑系列（含本机 ComfyUI 那套 Qwen 工作流）最多收 1–3 张输入图，人像也占一张，
# 所以参考图最多两张 —— 三件一起换不是没做，是接口不让。
MAX_INPUT_IMAGES = 3

VALID_MODES = ("single", "outfit", "hair")  # 顺序就是首页 tab 的顺序
REF_SLOTS = {"single": 1, "outfit": 2, "hair": 1}
# 参考图槽位的名字，一处定三处用：表单字段名、记录里的文件名主干、ComfyUI 的上传文件名。
# garment 打头是历史包袱 —— 换发型那次它装的是发型参考，改名的代价是老记录里的图全变孤儿。
REF_FIELDS = ("garment", "garment2")
REF_FILENAMES = tuple(f"{field}.jpg" for field in REF_FIELDS)  # 记录里的文件名主干就是字段名
SLOT_LABELS = {
    "single": ("衣服照片",),
    "outfit": ("上衣照片", "裤子/裙子照片"),
    "hair": ("发型参考",),
}

TRYON_PROMPT = (
    "把图像2中的衣服穿到图像1中的人身上，替换图像1人物原来的上衣。"
    "必须严格保持图像1中人物的脸部五官、发型、身材比例、姿势和背景不变。"
    "必须完整还原图像2中衣服的款式、颜色、纽扣、口袋、缝线、面料纹理和做旧细节。"
    "忽略图像2里的衣架、挂钩、背景和其他衣物。"
    "输出看起来像真实拍摄的照片，光影与图像1一致。"
)

OUTFIT_PROMPT = (
    # 第二张参考图在女装那边是裙子：指令只说裤子的话，裙子进去会换出一条裤子。
    "把图像2中的上衣和图像3中的下装（裤子或裙子）穿到图像1中的人身上，替换图像1人物原来的上衣和下装。"
    "必须严格保持图像1中人物的脸部五官、发型、身材比例、姿势和背景不变。"
    "必须完整还原图像2中上衣、图像3中下装的款式、颜色、纽扣、口袋、缝线、面料纹理和做旧细节。"
    "上衣下摆塞进腰头还是放在外面，按图像2本身的穿法，腰头、长度和褶皱要跟姿势对得上。"
    "忽略图像2和图像3里的衣架、挂钩、人台、背景和其他衣物。"
    "输出看起来像真实拍摄的照片，光影与图像1一致。"
)

HAIR_PROMPT = (
    "把图像2中的发型换到图像1中的人头上，替换图像1人物原来的发型。"
    "必须严格保持图像1中人物的脸部五官、脸型、肤色、表情、服装、身材比例、姿势和背景不变。"
    "必须完整还原图像2中发型的长度、层次、卷直、分缝、发色和光泽。"
    "发际线和鬓角要自然过渡到额头与颈部，不能像贴上去的一整块。"
    "只改头发，图像2里的身体、服装和背景一律不要带进来。"
    "输出看起来像真实拍摄的照片，光影与图像1一致。"
)

PROMPT_BY_MODE = {"single": TRYON_PROMPT, "outfit": OUTFIT_PROMPT, "hair": HAIR_PROMPT}


def prompt_for(mode: str) -> str:
    """这个分类该发的指令；分类不认识就明说，别猜成单件。"""
    if mode not in PROMPT_BY_MODE:
        raise ValueError(f"没有这个分类：{mode}")
    return PROMPT_BY_MODE[mode]
